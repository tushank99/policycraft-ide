"""GitHub GitOps Client.

Utilizes the low-level Git Data API (Trees & Blobs) to atomically commit 
an entire microservice scaffolding in 4 API calls, bypassing rate limits.
Applies enterprise branch protection and opens a baseline PR automatically.
"""

import json
import urllib.request
import urllib.error
import base64
import uuid
import sys
import os
from typing import Optional, Dict, Any

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from shared.logger import get_logger

logger = get_logger("github-client")

GITHUB_API_URL = "https://api.github.com"


def provision_to_github(org: str, repo_name: str, files: dict, token: str, request_data: dict) -> str:
    """Orchestrates the creation, commit, protection, and PR of the new repo."""
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "IDP-Provisioning-Service"
    }

    # 1. Handle Repo Collisions & Create Repository
    actual_repo_name = _create_repository(org, repo_name, headers)
    logger.info(f"Successfully initialized repository: {org}/{actual_repo_name}")

    try:
        # 2. Get Base Tree (from the auto-initialized main branch)
        main_ref = _api_request(f"/repos/{org}/{actual_repo_name}/git/refs/heads/main", headers=headers)
        latest_commit_sha = main_ref["object"]["sha"]
        
        base_commit = _api_request(f"/repos/{org}/{actual_repo_name}/git/commits/{latest_commit_sha}", headers=headers)
        base_tree_sha = base_commit["tree"]["sha"]

        # 3. Upload Blobs (Base64 safely handles both text and binaries)
        tree_elements = []
        for file_path, file_bytes in files.items():
            b64_content = base64.b64encode(file_bytes).decode('utf-8')
            blob_response = _api_request(
                f"/repos/{org}/{actual_repo_name}/git/blobs",
                method="POST",
                headers=headers,
                data={"content": b64_content, "encoding": "base64"}
            )
            tree_elements.append({
                "path": file_path,
                "mode": "100644",
                "type": "blob",
                "sha": blob_response["sha"]
            })

        # 4. Create New Tree
        new_tree = _api_request(
            f"/repos/{org}/{actual_repo_name}/git/trees",
            method="POST",
            headers=headers,
            data={"base_tree": base_tree_sha, "tree": tree_elements}
        )

        # 5. Create Commit
        new_commit = _api_request(
            f"/repos/{org}/{actual_repo_name}/git/commits",
            method="POST",
            headers=headers,
            data={
                "message": "chore: initial microservice scaffold",
                "tree": new_tree["sha"],
                "parents": [latest_commit_sha]
            }
        )

        # 6. Create Baseline Branch
        branch_name = "scaffold-baseline"
        _api_request(
            f"/repos/{org}/{actual_repo_name}/git/refs",
            method="POST",
            headers=headers,
            data={"ref": f"refs/heads/{branch_name}", "sha": new_commit["sha"]}
        )

        # 7. Apply Branch Protection to 'main'
        _apply_branch_protection(org, actual_repo_name, headers)

        # 8. Open Pull Request
        pr_url = _open_pull_request(org, actual_repo_name, branch_name, headers, request_data)
        return pr_url

    except Exception as e:
        logger.error(f"Provisioning failed. Rolling back repository {org}/{actual_repo_name}. Error: {e}")
        _api_request(f"/repos/{org}/{actual_repo_name}", method="DELETE", headers=headers)
        raise RuntimeError(f"GitOps provisioning failed and was rolled back: {e}")


