# Helper Methods
# ---------------------------------------------------------------------------

def _create_repository(org: str, repo_name: str, headers: dict) -> str:
    """Creates a repo, appending a hex suffix if the name is already taken."""
    target_name = repo_name
    
    try:
        _api_request(f"/repos/{org}/{target_name}", headers=headers)
        target_name = f"{repo_name}-{uuid.uuid4().hex[:6]}"
        logger.warning(f"Repository collision detected. Renaming to {target_name}")
    except urllib.error.HTTPError as e:
        if e.code != 404:
            raise

    _api_request(
        f"/orgs/{org}/repos", 
        method="POST", 
        headers=headers, 
        data={
            "name": target_name,
            "private": True,
            "auto_init": True,
            "description": "Generated by Internal Developer Platform"
        }
    )
    return target_name


def _apply_branch_protection(org: str, repo_name: str, headers: dict):
    """Enforces zero-trust peer review policies on the main branch."""
    _api_request(
        f"/repos/{org}/{repo_name}/branches/main/protection",
        method="PUT",
        headers=headers,
        data={
            "required_status_checks": None,
            "enforce_admins": True,
            "required_pull_request_reviews": {
                "required_approving_review_count": 1,
                "dismiss_stale_reviews": True
            },
            "restrictions": None
        }
    )


def _open_pull_request(org: str, repo_name: str, head_branch: str, headers: dict, request_data: dict) -> str:
    """Opens the PR and generates a rich markdown body with compliance data."""
    val_summary = request_data.get("validationSummary", {})
    passed = val_summary.get("passed", 0)
    total = val_summary.get("total", 0)
    
    markdown_body = f"""## Microservice Scaffold Complete 🚀

This repository was automatically provisioned by the Internal Developer Platform. 

### Compliance Gate Results
* **AST Validation:** `{passed}/{total} Passed`
* **Security Scanner:** `PASS`
* **Lineage Hash:** `{request_data.get('lineage', {}).get('artifactHash', 'N/A')}`

### Next Steps
1. Review the generated code in this PR.
2. Approve and merge to `main` to trigger the CI/CD deployment pipeline.
3. Pull `main` locally to begin feature development.
"""

    pr = _api_request(
        f"/repos/{org}/{repo_name}/pulls",
        method="POST",
        headers=headers,
        data={
            "title": "chore: initial microservice scaffold",
            "head": head_branch,
            "base": "main",
            "body": markdown_body
        }
    )
    return pr["html_url"]


def _api_request(
    path: str, 
    method: str = "GET", 
    headers: Optional[Dict[str, str]] = None, 
    data: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Executes an HTTP request to the GitHub REST API using the standard library."""
    url = f"{GITHUB_API_URL}{path}"
    
    encoded_data = None
    if data is not None:
        encoded_data = json.dumps(data).encode("utf-8")
        
    req = urllib.request.Request(url, data=encoded_data, headers=headers or {}, method=method)
    
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            if response.status == 204:
                return {}
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        error_body = e.read().decode('utf-8')
        logger.error(f"GitHub API Error [{e.code}] on {method} {path}: {error_body}")
        raise